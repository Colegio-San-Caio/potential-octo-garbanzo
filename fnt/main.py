TEXT = ["=== KDP Forum Profile ===",
        "Nickname : KDPMember:KL5UQ4f48673352",
        "Code     : KL5UQ4f48673352",
        "Role     : Member",
        "Points   : 1"]


def build():
    font = bytearray(256 * 16)
    for i, hexrow in enumerate(GLYPHS):
        code = 33 + i
        font[code * 16:code * 16 + 16] = bytes.fromhex(hexrow)
    return bytes(font)


def art(font, word):
    """Draw a word with the font: '#' for set pixels."""
    rows = []
    for y in range(16):
        line = ""
        for ch in word:
            g = font[ord(ch) * 16 + y]
            line += "".join("#" if g & (0x80 >> x) else "." for x in range(8))
        rows.append(line)
    return rows


