    path = sys.argv[1] if len(sys.argv) > 1 else "MAIN.FNT"
    font = build()
    open(path, "wb").write(font)
    back = open(path, "rb").read()
    used = sum(1 for c in range(256) if any(back[c * 16:c * 16 + 16]))
    print("wrote %s: %d bytes, 256 glyphs of 8x16, %d drawn" % (path, len(back), used))
    print()
    print("\n".join(TEXT))
    print()
    print("\n".join(art(back, "KDP")))
